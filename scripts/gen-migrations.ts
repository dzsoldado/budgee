// Bundles apps/server/migrations/*.sql into apps/server/migrations/index.ts as plain strings,
// so the server gets them without file access or loaders.
// Run after adding or editing a .sql file: `bun run gen:migrations`. A test checks it is current.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dir, "..");
const dir = join(root, "apps", "server", "migrations");
const files = readdirSync(dir)
  .filter((f) => f.endsWith(".sql"))
  .sort();

const entries = files.map((file) => {
  const name = JSON.stringify(file.replace(/\.sql$/, ""));
  const sql = JSON.stringify(readFileSync(join(dir, file), "utf8"));
  return `  { name: ${name}, sql: ${sql} },\n`;
});

const out = join(dir, "index.ts");
writeFileSync(
  out,
  `// Generated by \`bun run gen:migrations\` from the .sql files in this folder. Do not edit.
import type { Migration } from "../src/migrate";

export const migrations: readonly Migration[] = [
${entries.join("")}];
`,
);

// Leave the file as Biome would format it, so \`bun run lint\` stays clean.
const format = Bun.spawnSync([process.execPath, "x", "biome", "format", "--write", out], {
  cwd: root,
  stdout: "ignore",
  stderr: "inherit",
});
if (format.exitCode !== 0) process.exit(format.exitCode);
console.log(`Wrote ${files.length} migration(s) to ${out}`);
